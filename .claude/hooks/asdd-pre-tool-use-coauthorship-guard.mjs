#!/usr/bin/env node
// -----------------------------------------------------------------------------
// .claude/hooks/asdd-pre-tool-use-coauthorship-guard.mjs
//
// Hook PreToolUse (Bash + Write|Edit) que bloquea coautoría de IA en commits,
// MRs/PRs y contenido pre-escrito destinado a descripciones de MR/PR.
// Enforza la regla ASDD CORE-009 / WI #3492 y el fix R2 (v2.27.2) de
// BUILD-007 (bug C — "Co-Authored-By se escapa a MRs").
//
// Intercepta en matcher Bash:
//   1. git commit -m/--message con atribución de IA
//   2. glab mr create/update/edit con atribución de IA
//   3. gh pr create/edit con atribución de IA
//   4. glab api ...merge_requests (--method POST|PUT|PATCH) con atribución de IA
//   5. gh api ...pulls (--method POST|PATCH) con atribución de IA
//
// Intercepta en matcher Write|Edit:
//   6. Escritura de archivos candidatos a cuerpo de MR/PR — allowlist
//      positiva por basename (mr-body/pr-body/description/...) o paths
//      bajo .tmp/ — que contienen atribución de IA. Cubre el vector de
//      --description-file / --body-file / -F sin escanear toda la
//      documentación del proyecto (R2b — BUILD-007 bloqueante C3).
//      Excluye fixtures legítimas bajo test/, spec/, __tests__/ y
//      .claude/scripts/test-*.
//
// Patrones de IA detectados (case-insensitive), en paralelo (OR):
//   a) Co-Authored-By: <valor> con claude · anthropic · noreply@anthropic.com ·
//      openai · chatgpt · gpt-[0-9] · gemini
//   b) "🤖 Generated with/by", "Assisted by", "Written by" seguido de
//      Claude(Code) · Anthropic · OpenAI · ChatGPT · Gemini · Sonnet · Opus · Haiku
//
// Protocolo (Claude Code PreToolUse hooks):
//   - Entrada: JSON por stdin con { tool_name, tool_input: {...}, ... }
//   - Bloquear: process.stderr + process.exit(2)
//   - Permitir: process.exit(0) sin output
//
// Desactivación:
//   ASDD_COAUTHORSHIP_GUARD_ENABLED=false   (env o settings.json)
//   ASDD_COAUTHORSHIP_GUARD_DISABLE=1 (escape hatch auditable)
//
// Registro requerido en settings.json (manual — settings.json es deny-protegido):
//   En la entrada matcher "Bash" y en la entrada matcher "Write|Edit" de
//   PreToolUse, agregar al final del array de hooks:
//   { "type": "command", "command": "node $CLAUDE_PROJECT_DIR/.claude/hooks/asdd-pre-tool-use-coauthorship-guard.mjs" }
// -----------------------------------------------------------------------------

import { readFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

// ---- Config -----------------------------------------------------------------

const GUARD_ENABLED =
  process.env.ASDD_COAUTHORSHIP_GUARD_DISABLE !== "1" &&
  process.env.ASDD_COAUTHORSHIP_GUARD_ENABLED !== "false";

// ---- Helpers ----------------------------------------------------------------

function readStdin() {
  try {
    return readFileSync(0, "utf8");
  } catch {
    return "";
  }
}

function parseInput(raw) {
  if (!raw.trim()) return null;
  try {
    return JSON.parse(raw);
  } catch {
    // JSON malformado con contenido no-vacío: fallar CERRADO (#3639).
    process.stderr.write(
      "[ASDD coauthorship-guard] ERROR: stdin contiene JSON malformado — bloqueando por seguridad.\n"
    );
    process.exit(2);
  }
}

/**
 * Returns true if the command string creates or modifies a commit/MR/PR
 * (commands that can carry a commit/PR message susceptible to AI attribution).
 * C1: allowlist ampliada — cubre create/update/edit y llamadas API directas
 * de creación/edición de merge requests / pull requests.
 */
function isTargetCommand(command) {
  // git commit (with -m or --message flag)
  if (/\bgit\s+commit\b/.test(command)) return true;
  // glab mr create | update | edit
  if (/\bglab\s+mr\s+create\b/.test(command)) return true;
  if (/\bglab\s+mr\s+update\b/.test(command)) return true;
  if (/\bglab\s+mr\s+edit\b/.test(command)) return true;
  // gh pr create | edit
  if (/\bgh\s+pr\s+create\b/.test(command)) return true;
  if (/\bgh\s+pr\s+edit\b/.test(command)) return true;
  // glab api ...merge_requests con método de escritura (POST/PUT/PATCH)
  if (
    /\bglab\s+api\b/.test(command) &&
    /merge_requests/i.test(command) &&
    /--method[=\s]+["']?(POST|PUT|PATCH)["']?/i.test(command)
  ) {
    return true;
  }
  // gh api ...pulls con método de escritura (POST/PATCH)
  if (
    /\bgh\s+api\b/.test(command) &&
    /\bpulls\b/i.test(command) &&
    /--method[=\s]+["']?(POST|PATCH)["']?/i.test(command)
  ) {
    return true;
  }
  return false;
}

/**
 * Scans text (Bash command string, or file content pending Write/Edit) for
 * AI attribution patterns. Two independent detection vectors applied in
 * parallel (OR):
 *   1. Co-Authored-By trailer referencing an AI tool.
 *   2. Prose attribution independent of the trailer ("Generated with Claude
 *      Code", "🤖 Generated by Claude", "Assisted by Anthropic", etc — C2).
 * Returns { pattern, text } describing the match, or null if none found.
 */
function findAiAttribution(text) {
  const coauthorPattern =
    /Co-Authored-By:[^\n]*(?:claude|anthropic|noreply@anthropic\.com|openai|chatgpt|gpt-[0-9]|gemini)/i;
  const coMatch = coauthorPattern.exec(text);
  if (coMatch) {
    return { pattern: "Co-Authored-By", text: coMatch[0] };
  }

  const aiProsePattern =
    /(?:🤖\s*)?(?:Generated\s+(?:with|by)|Assisted\s+by|Written\s+by)\s*\[?(?:Claude(?:\s+Code)?|Anthropic|OpenAI|ChatGPT|Gemini|Sonnet|Opus|Haiku)\]?/i;
  const proseMatch = aiProsePattern.exec(text);
  if (proseMatch) {
    return { pattern: "Generated/Assisted/Written by (IA)", text: proseMatch[0] };
  }

  return null;
}

/**
 * C3: paths excluidos del análisis de contenido en matcher Write|Edit —
 * fixtures de test que legítimamente contienen el string como parte de su
 * verificación, y los propios scripts de test de este guard.
 */
function isExcludedPath(filePath) {
  const normalized = filePath.replace(/\\/g, "/");
  if (/(^|\/)(test|tests|spec|__tests__)\//i.test(normalized)) return true;
  if (/\.claude\/scripts\/test-[^/]*$/i.test(normalized)) return true;
  return false;
}

/**
 * C3 (refinado R2b): determina si el archivo escrito es candidato razonable
 * a contener el cuerpo de un MR/PR. Usa ALLOWLIST POSITIVA en vez de escanear
 * todo .md/.txt — evita falsos positivos sobre documentación del template
 * (docs/tech/, SKILL.md, planes maestros) que legítimamente contiene el
 * string "Co-Authored-By" como parte de su diagnóstico/contenido.
 *
 * Candidato si:
 *   a) el basename contiene un hint explícito de cuerpo de MR/PR
 *      (mr-body, pr-body, mr_body, pr_body, merge-request, pull-request,
 *      mr-desc, pr-desc, description), o
 *   b) el path está bajo .tmp/ (staging efímero típico de --description-file
 *      / --body-file antes de invocar glab/gh — vector 2).
 *
 * El hint se evalúa sobre el BASENAME, no el path completo: evaluarlo sobre
 * el path completo generaba falsos positivos (ej. el directorio
 * "asdd-tech-lead-create-mr" contiene la subcadena "-mr" y bloqueaba
 * su propio SKILL.md).
 */
function isTargetPath(filePath) {
  const normalized = filePath.replace(/\\/g, "/");
  const basename = normalized.split("/").pop() || "";
  const underTmp = /(^|\/)\.tmp\//i.test(normalized);
  const hasBodyHint =
    /(mr[-_]body|pr[-_]body|merge-request|pull-request|mr-desc|pr-desc|description)/i.test(basename);
  return underTmp || hasBodyHint;
}

// ---- Main -------------------------------------------------------------------

export function getCoauthorshipDecision(input, environment = process.env) {
  const enabled =
    environment.ASDD_COAUTHORSHIP_GUARD_DISABLE !== "1" &&
    environment.ASDD_COAUTHORSHIP_GUARD_ENABLED !== "false";
  if (!enabled || input === null) return null;

  const toolName = input.tool_name || input.toolName;
  const toolInput = input.tool_input || input.toolInput || {};

  if (toolName === "Bash") {
    const command = toolInput.command || "";

    // Solo inspeccionar comandos relevantes (C1)
    if (!isTargetCommand(command)) return null;

    const matched = findAiAttribution(command);
    if (!matched) return null;

    return { decision: "deny", reason:
      `[ASDD CORE-009 / WI #3492] Coautoría de IA detectada en el mensaje de commit/MR/PR ` +
        `(patrón: ${matched.pattern}): "${matched.text}". ` +
        `Usar conventional commits sin atribución de IA. ` +
        `Ver regla en .claude/skills/asdd-tech-lead-commit/SKILL.md y ` +
        `.claude/skills/asdd-tech-lead-create-mr/SKILL.md`
    };
  }

  if (toolName === "Write" || toolName === "Edit") {
    const filePath = toolInput.file_path || toolInput.path || toolInput.filePath || "";
    if (!filePath) return null;
    if (isExcludedPath(filePath)) return null;
    if (!isTargetPath(filePath)) return null;

    const content =
      toolName === "Write"
        ? toolInput.content || ""
        : toolInput.new_string || toolInput.newString || "";
    if (!content) return null;

    const matched = findAiAttribution(content);
    if (!matched) return null;

    return { decision: "deny", reason:
      `[ASDD CORE-009 / WI #3492] Coautoría de IA detectada al escribir "${filePath}" ` +
        `(patrón: ${matched.pattern}): "${matched.text}". ` +
        `El contenido de descripciones de MR/PR no puede llevar atribución de IA. ` +
        `Ver regla en .claude/skills/asdd-tech-lead-create-mr/SKILL.md`
    };
  }
  return null;
}

function main() {
  const result = getCoauthorshipDecision(parseInput(readStdin()));
  if (!result) process.exit(0);
  process.stderr.write(`${result.reason}\n`);
  process.exit(2);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
